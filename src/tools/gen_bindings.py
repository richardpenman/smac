#!/usr/bin/env python3
"""Generate function bindings between reconstructed code and the original terranx.exe.

Engine headers declare reconstructed functions with the address of the original:

    ADDR(0x5C86E0) void GAMEAPI world_build();
    ADDR_NATIVE(0x64601D) int GAMEAPI game_rand();   // hybrid builds always use the original

A function counts as implemented when a .cpp file under the scanned directories defines it.

Outputs (written to <outdir>):
  native_stubs.cpp   native build: aborting stubs for declared-but-unimplemented functions
  hybrid_bindings.cpp hybrid build: forwarders to the original for unimplemented/ADDR_NATIVE
                     functions, plus the patch table of implemented functions
  status.tsv         addr, name, state (implemented|native_only|missing), header
Usage: gen_bindings.py <outdir> <src_dir>...
"""
import os
import re
import sys

DECL = re.compile(
    r"ADDR(_NATIVE)?\(\s*(0x[0-9A-Fa-f]+)\s*\)\s*"
    r"((?:[\w:<>]+[\s\*&]+)+?)(GAMEAPI\s+|THISCALL\s+)?(\w+)\s*\(([^)]*)\)\s*;", re.S)


def split_params(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch in "(<[" and 1 or 0
        depth -= ch in ")>]" and 1 or 0
        cur += ch
    out.append(cur.strip())
    return out


def param_name(p, i):
    m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", p)
    base = re.sub(r"\[[^\]]*\]", "", p)
    # unnamed parameter: the last identifier is a type keyword
    if not m or len(base.replace("*", " ").replace("&", " ").split()) < 2 or m.group(1) in (
            "int", "char", "short", "long", "unsigned", "signed", "double", "float", "bool", "void") or \
            m.group(1).endswith("_t") or m.group(1)[0].isupper():
        return None
    return m.group(1)


def main():
    outdir, srcdirs = sys.argv[1], sys.argv[2:]
    decls = {}
    defined = set()
    for d in srcdirs:
        for root, _, files in os.walk(d):
            for f in files:
                path = os.path.join(root, f)
                text = open(path, encoding="utf-8", errors="replace").read()
                if f.endswith(".h"):
                    for m in DECL.finditer(text):
                        native_only, addr, ret, cc, name, params = m.groups()
                        cc = (cc or "GAMEAPI").strip()
                        decls[name] = dict(addr=int(addr, 16), ret=" ".join(ret.split()), name=name, cc=cc,
                                           params=split_params(params), native_only=bool(native_only),
                                           header=os.path.relpath(path, d))
                elif f.endswith(".cpp") and not f.startswith(("native_stubs", "hybrid_bindings")):
                    clean = re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.S)
                    for m in re.finditer(r"^[A-Za-z_][\w:<>\s\*&]*?\b(\w+)\s*\([^;{]*\)\s*(?:const\s*)?\{",
                                         clean, re.M):
                        defined.add(m.group(1))
                    # hybrid shadow thunks: SHADOWABLE(name)(...) { ... } defines name
                    for m in re.finditer(r"\bSHADOWABLE\((\w+)\)\s*\(", clean):
                        defined.add(m.group(1))
    os.makedirs(outdir, exist_ok=True)
    native, hybrid, table, status = [], [], [], []
    for name, d in sorted(decls.items(), key=lambda kv: kv[1]["addr"]):
        params = []
        for i, p in enumerate(d["params"]):
            n = param_name(p, i)
            if n is None:
                n = f"a{i}"
                p = f"{p} {n}"
            params.append((p, n))
        sig_params = ", ".join(p for p, _ in params)
        args = ", ".join(n for _, n in params)
        ret = d["ret"]
        is_void = ret == "void"
        implemented = name in defined
        state = "native_only" if d["native_only"] else ("implemented" if implemented else "missing")
        status.append(f"{d['addr']:08X}\t{name}\t{state}\t{d['header']}")
        if not implemented:
            native.append(f"{ret} {d['cc']} {name}({sig_params}) {{ smac_unimplemented(\"{name}\", 0x{d['addr']:06X}); }}")
        if d["native_only"] or not implemented:
            ptype = f"{ret}({d['cc']}*)({', '.join(p for p, _ in params)})"
            call = f"reinterpret_cast<{ptype}>(0x{d['addr']:06X})({args})"
            hybrid.append(f"{ret} {d['cc']} {name}({sig_params}) {{ {'' if is_void else 'return '}{call}; }}")
        else:
            table.append(f"    {{0x{d['addr']:06X}, reinterpret_cast<void*>(&{name}), \"{name}\"}},")
    includes = sorted({d["header"] for d in decls.values()})
    inc = "".join(f'#include "{h}"\n' for h in includes)
    with open(os.path.join(outdir, "native_stubs.cpp"), "w") as f:
        f.write("// Generated by tools/gen_bindings.py. Do not edit.\n#ifndef SMACX_HYBRID\n")
        f.write(inc + '#include "engine/unimplemented.h"\n\n' + "\n".join(native) + "\n#endif\n")
    with open(os.path.join(outdir, "hybrid_bindings.cpp"), "w") as f:
        f.write("// Generated by tools/gen_bindings.py. Do not edit.\n#ifdef SMACX_HYBRID\n")
        f.write(inc + '#include "engine/hybrid_patch.h"\n\n' + "\n".join(hybrid) + "\n\n")
        f.write("const HybridPatch kHybridPatches[] = {\n" + "\n".join(table) + "\n    {0, nullptr, nullptr},\n};\n#endif\n")
    with open(os.path.join(outdir, "status.tsv"), "w") as f:
        f.write("addr\tname\tstate\theader\n" + "\n".join(status) + "\n")
    impl = sum(1 for s in status if "\timplemented\t" in s)
    print(f"gen_bindings: {len(decls)} declared, {impl} implemented, {len(decls) - impl} not")


if __name__ == "__main__":
    main()
