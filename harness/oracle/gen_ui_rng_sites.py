#!/usr/bin/env python3
"""Generate ui_rng_sites.h: call sites of the shared RNGs that live in non-engine (UI/system) code.
The oracle redirects these to private generators so UI timing cannot perturb gameplay randomness."""
import re, bisect, csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
idx = list(csv.DictReader(open(f'{ROOT}/re/out/index.tsv'), delimiter='\t'))
A = [int(r['addr'], 16) for r in idx]
asm = open(f'{ROOT}/re/out/terranx.asm').read().splitlines()
targets = {'625810': 'game_random', '64601d': 'crt_rand'}
out = {k: [] for k in targets.values()}
for l in asm:
    m = re.match(r'\s*([0-9a-f]+):\s.*call +0x([0-9a-f]+)$', l)
    if not m or m.group(2) not in targets: continue
    a = int(m.group(1), 16); i = bisect.bisect_right(A, a) - 1
    r = idx[i]
    if r['kind'] in ('ui', 'sys'):
        out[targets[m.group(2)]].append((a, r['name']))
with open(f'{ROOT}/harness/oracle/ui_rng_sites.h', 'w') as f:
    f.write('/* Generated by gen_ui_rng_sites.py: RNG call sites in UI/system code. */\n')
    for k, v in out.items():
        f.write(f'static const uint32_t ui_sites_{k}[] = {{\n')
        for a, n in v: f.write(f'    0x{a:06X}, /* {n} */\n')
        f.write('};\n')
for k, v in out.items(): print(k, len(v), sorted(set(n for _, n in v)))
